    private void btnanalyze_surnameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnanalyze_surnameActionPerformed
        // TODO add your handling code here:
        try{
            Instances data = DataSource.read("saleslindogss.arff");
            data.setClassIndex(1);
            SimpleLinearRegression model = new SimpleLinearRegression();
            model.buildClassifier(data);
            ///
            Evaluation eval = new Evaluation(data);
            eval.evaluateModel(model, data);
            
            double mae = eval.meanAbsoluteError();
            double rmse = eval.rootMeanSquaredError();
            double correlation = eval.correlationCoefficient();
            double rSquared = correlation * correlation;
            
            MAEEval(mae);
            RMSEEval(rmse);
            R2EVAL(rSquared);
            CORREEval(correlation);
            
            double month = Double.parseDouble(txtmonth_surname.getText());
            
            DenseInstance test = new DenseInstance(data.numAttributes());
            test.setDataset(data);
            test.setValue(0, month);
            
            double prediction = model.classifyInstance(test);
            lblpredictivevalue_summary.setText("Prediction Sales: " + String.format("%.2f", prediction));
        }
        catch (Exception ex)
        {
            System.out.println(ex.getMessage());
        }
    }//GEN-LAST:event_btnanalyze_surnameActionPerformed

