    private void loaddataset()
    {
        try{
            Instances data = DataSource.read("saleslindogss.arff");
            txtarff_surname.setText(data.toString());
            lblrow.setText("Row: " + data.numInstances());
            String output = "Month\tSales\n";
            for (int i = 0; i < data.numInstances(); i++)
            {
                double month = data.instance(i).value(0);
                double sales = data.instance(i).value(1);
                output += month + "\t" + sales + "\n";
            }
            txttabularview_surname.setText(output);
        }
        catch(Exception ex)
        {
            System.out.println(ex.getMessage());
        }
    }

