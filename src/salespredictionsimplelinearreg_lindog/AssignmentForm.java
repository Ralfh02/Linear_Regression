    private void btnanalyze_surnameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnanalyze_surnameActionPerformed
        // TODO add your handling code here:
        try{
            Instances data = DataSource.read("assignment.arff");
            data.setClassIndex(1);
            
            //data.randomize(new java.util.Random(42));
            
            int trainSize = (int) Math.round(data.numInstances() * 0.80);
            int testSize = data.numInstances() - trainSize;
            
            lblTrain.setText(lblTrain.getText() + " " + trainSize);
            jLabel14.setText(jLabel14.getText() + " " + testSize);
            
            Instances trainData = new Instances(data, 0, trainSize);
            Instances testData = new Instances(data, trainSize, testSize);
            
            // Training
            SimpleLinearRegression model = new SimpleLinearRegression();
            model.buildClassifier(trainData);
            
           Evaluation trainEval = new Evaluation(trainData);
           trainEval.evaluateModel(model, trainData);
           
           double trainMae = trainEval.meanAbsoluteError();
           double trainRmse = trainEval.rootMeanSquaredError();
           double trainCorrelation = trainEval.correlationCoefficient();
           double trainRSquared = trainCorrelation * trainCorrelation;
           
           lblMAE.setText(lblMAE.getText() + MAEEval(trainMae));
           lblRMSE.setText(lblRMSE.getText() + RMSEEval(trainRmse));
           lblCORR.setText(lblCORR.getText() + CORREEval(trainCorrelation));
           lblR2.setText(lblR2.getText() + R2Eval(trainRSquared));

           Evaluation testEval = new Evaluation(trainData);
           testEval.evaluateModel(model, testData);
           double testMae = testEval.meanAbsoluteError();
           double testRmse = testEval.rootMeanSquaredError();
           double testCorrelation = testEval.correlationCoefficient();
           double testRSquared = testCorrelation * testCorrelation;

           lblMAET.setText(lblMAET.getText() + MAEEval(testMae));
           lblRMSET.setText(lblRMSET.getText() + RMSEEval(testRmse));
           lblCORRT.setText(lblCORRT.getText() + CORREEval(testCorrelation));
           lblR2T.setText(lblR2T.getText() + R2Eval(testRSquared));

            double month = Double.parseDouble(txtmonth_surname.getText());

            DenseInstance predictionInstance = new DenseInstance(data.numAttributes());
            predictionInstance.setDataset(data);
            predictionInstance.setValue(0, month);

            double prediction = model.classifyInstance(predictionInstance);
            lblpredictivevalue_summary.setText("Prediction Sales: " + String.format("%.2f", prediction));
            
            double trainPrediction = model.classifyInstance(trainData.instance(0));
            double actualTrainSales = trainData.instance(0).classValue();
            double trainMonth = trainData.instance(0).value(0);
            lblPreT.setText("Prediction Sales: " + String.format("Month %.0f: Predicted %.2f | Actual %.2f",
                        trainMonth,
                        trainPrediction,
                        actualTrainSales));

        }
        catch (Exception ex)
        {
            System.out.println(ex.getMessage());
        }
    }//GEN-LAST:event_btnanalyze_surnameActionPerformed

