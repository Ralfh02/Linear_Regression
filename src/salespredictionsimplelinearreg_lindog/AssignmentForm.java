    private void loaddataset()
    {
       try {
        // 1. Load Raw ARFF File (Make sure assignment.arff is in your project's root folder)
        DataSource source = new DataSource("assignment.arff");
        rawData = source.getDataSet();
        
        if (rawData == null) {
            System.out.println("Error: Failed to load dataset from assignment.arff");
            return;
        }
        
        txtarff_surname.setText(rawData.toString());

        // 2. Initialize and clean the dataset safely
        cleanedData = new Instances(rawData);
        for (int i = cleanedData.numInstances() - 1; i >= 0; i--) {
            if (cleanedData.instance(i).isMissing(0) || cleanedData.instance(i).isMissing(1)) {
                cleanedData.delete(i); 
            } else if (cleanedData.instance(i).value(1) < 0) {
                cleanedData.instance(i).setValue(1, 0.0); 
            }
        }

        lblrow.setText("Total Rows (Cleaned): " + cleanedData.numInstances());

        // Populate Tabular View
        StringBuilder output = new StringBuilder("Month\tSales\n");
        for (int i = 0; i < cleanedData.numInstances(); i++) {
            double month = cleanedData.instance(i).value(0);
            double sales = cleanedData.instance(i).value(1);
            output.append((int) month).append("\t").append(String.format("%.2f", sales)).append("\n");
        }
        txttabularview_surname.setText(output.toString());

    } catch (Exception ex) {
        System.out.println("Error loading dataset: " + ex.getMessage());
    }
    }


