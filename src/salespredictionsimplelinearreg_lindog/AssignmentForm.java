    private String CORREEval(double val)
{
    String output = "";

    // Handle invalid correlation
    if (Double.isNaN(val)) {
        return "N/A - Cannot calculate correlation";
    }

    // Use absolute value for strength
    double strength = Math.abs(val);

    if (strength >= 0.90 && strength <= 1.00)
    {
        output = String.format("%.4f", val)
                + " - Very Strong (Sukat ng lapit ng predicted at actual values)";
    }
    else if (strength >= 0.70)
    {
        output = String.format("%.4f", val)
                + " - Strong (Sukat ng lapit ng predicted at actual values)";
    }
    else if (strength >= 0.50)
    {
        output = String.format("%.4f", val)
                + " - Moderate (Sukat ng lapit ng predicted at actual values)";
    }
    else if (strength >= 0.30)
    {
        output = String.format("%.4f", val)
                + " - Weak (Sukat ng lapit ng predicted at actual values)";
    }
    else
    {
        output = String.format("%.4f", val)
                + " - Very Weak (Sukat ng lapit ng predicted at actual values)";
    }

    return output;
}
